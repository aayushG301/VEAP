interface I18nContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const defaultT = (key: string, params?: Record<string, string | number>): string => {
  let template = translations.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      template = template.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return template;
};

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: defaultT,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem("veap_lang");
      if (saved && (saved === "en" || saved === "hi" || saved === "mr")) {
        return saved;
      }
    } catch {
      // ignore localStorage errors
    }
    return "en";
  });

  const setLang = (next: Language) => {
    setLangState(next);
    try {
      localStorage.setItem("veap_lang", next);
      document.documentElement.lang = next;
    } catch {
      // ignore
    }
  };

  useEffect(() => {
    try {
      document.documentElement.lang = lang;
    } catch {
      // ignore
    }
  }, [lang]);

  const t = (key: string, params?: Record<string, string | number>): string => {
    let template = translations[lang]?.[key] ?? translations.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        template = template.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return template;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

export function LanguagePicker({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();

  return (
    <div className={`lang-picker ${className}`} role="group" aria-label="Language selection">
      {LANGUAGES.map((item) => (
        <button
          key={item.code}
          type="button"
          className={`lang-btn ${lang === item.code ? "active" : ""}`}
          onClick={() => setLang(item.code)}
          aria-pressed={lang === item.code}
          title={item.name}
        >
          <span className="lang-flag">{item.flag}</span>
          <span className="lang-name">{item.nativeName}</span>
        </button>
      ))}
    </div>
  );
}
